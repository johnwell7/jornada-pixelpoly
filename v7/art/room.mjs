export async function loadArtImage(src) {
  const img = new Image();
  img.src=src;
  await img.decode();
  return img;
}

export function loadRoom() {
  return loadArtImage(roomSource);
}

export function drawRoom(g, image) {
  g.drawImage(image,0,0,world.width,world.height);
}

export function drawScenery(g, id, image, time) {
  const points=masks[id];
  if (!points) return;
  const unit=world.width/referenceWidth;
  g.save();
  g.beginPath();
  points.forEach(([x,y],i)=>i===0?g.moveTo(x*unit,y*unit):g.lineTo(x*unit,y*unit));
  g.closePath();
  g.clip();
  drawRoom(g,image);
  g.restore();
  if (id==='lantern') {
    g.save();
    g.globalCompositeOperation='screen';
    g.globalAlpha=.12+.07*Math.sin(time*6);
    g.fillStyle='#ffb52b';
    g.fillRect(296,147,3,7);
    g.restore();
  }
}

